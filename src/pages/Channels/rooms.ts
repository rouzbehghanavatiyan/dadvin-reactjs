export const courtChannels = Object.keys(channelRooms);

const roomNumbers = ["۱", "۲", "۳", "۴", "۵", "۶", "۷", "۸", "۹", "۱۰"];
const occupancyPattern = [5, 9, 3, 7, 1, 8, 4, 6, 2, 5];

export const roomCapacity = 10;

function persianNumber(value: number) {
  return String(value).replace(/\d/g, (digit) => "۰۱۲۳۴۵۶۷۸۹"[Number(digit)]);
}

function occupiedIn(channel: string, index: number) {
  if (index === 0) return roomCapacity;
  const shift = Array.from(channel).reduce((sum, char) => sum + char.charCodeAt(0), 0);
  return occupancyPattern[(index + shift) % occupancyPattern.length];
}

export function roomsFor(channel: string) {
  const titles = channelRooms[channel as keyof typeof channelRooms];
  if (!titles) return [];
  return titles.map((title, index) => {
    const occupied = occupiedIn(channel, index);
    const full = index === 0;
    return {
      id: `${channel}-${index + 1}`,
      number: roomNumbers[index],
      title,
      occupied,
      capacity: roomCapacity,
      full,
      occupancy: full
        ? "ظرفیت تکمیل است"
        : `${persianNumber(occupied)} از ${persianNumber(roomCapacity)}`,
    };
  });
}
